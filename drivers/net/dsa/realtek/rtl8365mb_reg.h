#define  RTL8365MB_EXT_TXC_DLY_EXT0_RGMII_TX_DELAY_MASK        GENMASK(2, 0)
#define  RTL8365MB_EXT_TXC_DLY_EXT1_RGMII_TX_DELAY_MASK        GENMASK(5, 3)
#define  RTL8365MB_EXT_TXC_DLY_EXT2_RGMII_TX_DELAY_MASK        GENMASK(8, 6)
#define  RTL8365MB_EXT_TXC_DLY_EXT0_GMII_TX_DELAY_MASK         GENMASK(11, 9)
#define  RTL8365MB_EXT_TXC_DLY_EXT1_GMII_TX_DELAY_MASK         GENMASK(14, 12)

