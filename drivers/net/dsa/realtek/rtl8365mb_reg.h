/* This is another external interface delay configuration that may overlap
 * with RTL8365MB_EXT_RGMXF_TXDELAY_MASK from RTL8365MB_EXT_RGMXF_REG[012].
 *
 * During init, the specific initialization for chips like 0x6367 set both EXT1
 * and EXT2 TX delay to 2 (both in this driver jam table and in vendor code).
 *
 * In vendor code, when the port mode is set to GMII in a chip_id 0x6367, EXT0
 * is changed to 6 and EXT1 to 5. However, this driver does not touch this
 * register in rtl8365mb_ext_config_rgmii(). Instead, it sets the TX delay only
 * in RTL8365MB_EXT_RGMXF_TXDELAY_MASK in RTL8365MB_EXT_RGMXF_REG[012]. In
 * vendor code, the RTL8365MB_EXT_RGMXF_REG[012] is only set in a generic RGMII
 * delay set function, not specific for a chip_id.
 *
 * If TX delay related issues appear in the future, this register is a good
 * starting point for investigation.
 */
